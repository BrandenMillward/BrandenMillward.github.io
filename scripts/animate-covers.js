// Writes the motion <style> block into each project cover.
//
// The covers load through <img>, so page CSS cannot reach inside them: every cover carries its
// own copy of the rules. The markup (which element plays which part, and when) is hand-authored
// in each SVG through classes and an inline --d delay. This script only owns the CSS, so the
// timing language stays identical across covers.
//
// Every animation shares one cycle length T per cover, so all parts stay phase-locked across
// loops. Keyframe percentages are therefore derived from T, which is why this is generated.
//
//   node scripts/animate-covers.js
const fs = require('fs');
const path = require('path');
const IMG = path.join(__dirname, '..', 'images');

const A = '#696fb4';
const EASE = 'cubic-bezier(0.4, 0, 0.2, 1)';   // signature curve, on-screen travel
const OUT = 'cubic-bezier(0, 0, 0.2, 1)';      // decelerate, arrivals
const IN = 'cubic-bezier(0.4, 0, 1, 1)';       // accelerate, wind-up

// Cycle length per cover, in ms. Longer only where the story has more beats.
const COVERS = {
  'research-engine': 4800,
  'doc-platform': 4800,
  'video-agent': 4800,
  'enrichment-middleware': 4800,
  'policy-grader': 4800,
  'onboarding-agent': 7200,
  'sharing-audit': 4800,
  'market-landscape': 4800,
  'agent-monitor': 4800,
  'repo-docs': 4800,
};

function css(T, extra) {
  const p = ms => `${+(ms / T * 100).toFixed(2)}%`;
  const s = `${T / 1000}s`;
  // A streak, not a dot: the covers render at roughly half size, where a dot is ~2px and
  // reads as still. The head runs out ahead (accelerating), the tail follows it in
  // (decelerating), then the tail is absorbed into the node it reached.
  const hop = (name, ms) => `
    @keyframes ${name} {
      0%       { stroke-dasharray: 0 200; stroke-dashoffset: 0; opacity: 0; animation-timing-function: ${IN}; }
      ${p(20)} { opacity: 1; }
      ${p(ms * 0.3)} { stroke-dasharray: 30 200; stroke-dashoffset: 0; animation-timing-function: ${OUT}; }
      ${p(ms)} { stroke-dasharray: 30 200; stroke-dashoffset: -70; opacity: 1; animation-timing-function: ${IN}; }
      ${p(ms + 160)}, 100% { stroke-dasharray: 0 200; stroke-dashoffset: -100; opacity: 0; }
    }`;
  return `
    /* Motion is decoration: under reduced motion every rule below switches off and the
       diagram is exactly as authored. Generated by scripts/animate-covers.js, edit there.
       .pkt    a streak riding a duplicate of a connector (pathLength=100)
       .emit   source winds up, then releases
       .pop    node reacts as a packet lands (.pop-s for large shapes)
       .ping   copy of an output ring that expands and fades
       .write  stroke redraws left to right (pathLength=100)
       .shake  a flagged gap
       .spin   one eased turn, origin set inline
       .breathe ambient, the only part with no delay */
    .pkt {
      fill: none; stroke: ${A}; stroke-width: 4; stroke-linecap: round;
      stroke-dasharray: 0 200; opacity: 0;
      animation: hop ${s} var(--d, 0s) infinite both;
    }
    .pkt.l { animation-name: hop-l; }
    .emit, .pop, .pop-s, .ping, .shake { transform-box: fill-box; transform-origin: center; }
    .emit  { animation: emit ${s} var(--d, 0s) infinite both; }
    .pop   { animation: pop ${s} var(--d, 0s) infinite both; }
    .pop-s { animation: pop-s ${s} var(--d, 0s) infinite both; }
    .ping  { opacity: 0; animation: ping ${s} var(--d, 0s) infinite both; }
    .write { stroke-dasharray: 100 100; animation: write ${s} var(--d, 0s) infinite both; }
    .shake { animation: shake ${s} var(--d, 0s) infinite both; }
    .spin  { transform-box: view-box; animation: spin ${s} var(--d, 0s) infinite both; }
    .breathe { animation: breathe ${s} ease-in-out infinite; }
    ${hop('hop', 600)}
    ${hop('hop-l', 800)}
    @keyframes emit {
      0%        { transform: scale(1); animation-timing-function: ${IN}; }
      ${p(240)} { transform: scale(0.85); animation-timing-function: ${OUT}; }
      ${p(420)} { transform: scale(1.15); animation-timing-function: ${EASE}; }
      ${p(700)}, 100% { transform: scale(1); }
    }
    @keyframes pop {
      0%        { transform: scale(1); animation-timing-function: ${OUT}; }
      ${p(180)} { transform: scale(1.5); animation-timing-function: ${EASE}; }
      ${p(500)}, 100% { transform: scale(1); }
    }
    @keyframes pop-s {
      0%        { transform: scale(1); animation-timing-function: ${OUT}; }
      ${p(200)} { transform: scale(1.1); animation-timing-function: ${EASE}; }
      ${p(560)}, 100% { transform: scale(1); }
    }
    @keyframes ping {
      0%         { transform: scale(1); opacity: 0.9; animation-timing-function: ${OUT}; }
      ${p(1000)}, 100% { transform: scale(2.4); opacity: 0; }
    }
    @keyframes write {
      0%        { stroke-dashoffset: 100; animation-timing-function: cubic-bezier(0.2, 0, 0, 1); }
      ${p(600)}, 100% { stroke-dashoffset: 0; }
    }
    @keyframes shake {
      0%, ${p(360)}, 100% { transform: translateX(0); }
      ${p(70)}  { transform: translateX(4px); }
      ${p(140)} { transform: translateX(-4px); }
      ${p(210)} { transform: translateX(3px); }
      ${p(280)} { transform: translateX(-2px); }
    }
    @keyframes spin {
      0%        { transform: rotate(0deg); animation-timing-function: ${EASE}; }
      ${p(900)}, 100% { transform: rotate(360deg); }
    }
    @keyframes breathe { 50% { opacity: 0.5; } }${extra ? extra(p, s) : ''}
    @media (prefers-reduced-motion: reduce) {
      .pkt, .ping, .sweep { display: none; }
      .emit, .pop, .pop-s, .write, .shake, .spin, .breathe { animation: none; }
    }
  `;
}

// One-off beats that only a single cover has.
const EXTRA = {
  // the time budget fills linearly (a progress bar, the one place linear is right), then clears
  'enrichment-middleware': (p, s) => `
    .sweep {
      fill: none; stroke: ${A}; stroke-width: 2.5; stroke-linecap: round;
      stroke-dasharray: 100 100;
      animation: sweep ${s} var(--d, 0s) infinite both;
    }
    @keyframes sweep {
      0%         { stroke-dashoffset: 100; opacity: 1; animation-timing-function: linear; }
      ${p(2100)} { stroke-dashoffset: 0; }
      ${p(2700)} { opacity: 1; }
      ${p(3100)}, 100% { stroke-dashoffset: 0; opacity: 0; }
    }`,
};

for (const [name, T] of Object.entries(COVERS)) {
  const f = path.join(IMG, name + '.svg');
  const src = fs.readFileSync(f, 'utf8');
  if (!/<style>[\s\S]*?<\/style>/.test(src)) throw new Error(`${name}: no <style> block`);
  fs.writeFileSync(f, src.replace(/<style>[\s\S]*?<\/style>/, `<style>${css(T, EXTRA[name])}</style>`));
  console.log('wrote', name);
}
